/** 对账：返回每行 {…row, actual, diff, ok} */
export function reconcile(values) {
  return RECONCILE.map((row) => {
    const actual = values[row.id];
    const diff = actual - row.expected;
    return { ...row, actual, diff, ok: Math.abs(diff) <= row.tol };
  });
}
